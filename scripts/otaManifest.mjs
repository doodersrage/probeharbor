/**
 * Signed OTA manifest for the probe firmware (public/firmware/ota.json).
 *
 * The OTA image is the app part of the merged image /flash already serves:
 * bytes from OTA_APP_OFFSET to the end of public/firmware/probeharbor-probe-<chip>.bin.
 * For each chip the manifest gives that image's size and SHA-256, and an
 * ECDSA P-256 signature (DER, base64) over otaMessage(). The probe checks
 * the signature with the public key compiled into it (src/ota_pubkey.h),
 * then the hash of what it downloaded, and only takes a higher version.
 * The private key never leaves the owner's machine (see firmware-ota.mjs).
 *
 * Changing otaMessage() breaks every probe already in the field: bump the
 * "probeharbor-ota-v1" tag and keep the old form working in the firmware.
 */
import { createHash, createPublicKey, sign, verify } from "node:crypto";

/**
 * @typedef {{ url: string, offset: number, size: number, sha256: string, sig: string }} OtaBuild
 * @typedef {{ format: number, version: string, rollout_pct: number, builds: Record<string, OtaBuild> }} OtaManifest
 */

export const OTA_APP_OFFSET = 0x10000;
const ESP_IMAGE_MAGIC = 0xe9;

/**
 * The exact bytes that are signed for one chip's image.
 * @param {{ chip: string, version: string, size: number, sha256: string }} fields
 */
export function otaMessage({ chip, version, size, sha256 }) {
  return `probeharbor-ota-v1\n${chip}\n${version}\n${size}\n${sha256}\n`;
}

/**
 * The app image inside a merged /flash image.
 * @param {Buffer} merged
 */
export function appSlice(merged) {
  if (merged.length <= OTA_APP_OFFSET + 24 || merged[OTA_APP_OFFSET] !== ESP_IMAGE_MAGIC) {
    throw new Error(`no ESP app image at offset 0x${OTA_APP_OFFSET.toString(16)}`);
  }
  return merged.subarray(OTA_APP_OFFSET);
}

/**
 * "1.4.0" > "1.3.10"? Numeric per part; anything after "-" is ignored.
 * @param {string} a
 * @param {string} b
 * @returns {number}
 */
export function compareVersions(a, b) {
  const parts = (/** @type {string} */ v) => String(v).split("-")[0].split(".").map((n) => Number.parseInt(n, 10) || 0);
  const [x, y] = [parts(a), parts(b)];
  for (let i = 0; i < Math.max(x.length, y.length); i++) {
    const d = (x[i] ?? 0) - (y[i] ?? 0);
    if (d !== 0) return Math.sign(d);
  }
  return 0;
}

/**
 * images: [{ chip, merged: Buffer }]. Returns the manifest object.
 * rolloutPct: probes whose bucket (0–99) is below it take the update.
 * urlBase: where the images are served (public/firmware → "/firmware").
 * @param {{ version: string, images: { chip: string, merged: Buffer }[], privateKeyPem: string, rolloutPct?: number, urlBase?: string }} input
 * @returns {OtaManifest}
 */
export function buildOtaManifest({ version, images, privateKeyPem, rolloutPct = 100, urlBase = "/firmware" }) {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`version must be x.y.z, got "${version}"`);
  if (!Number.isInteger(rolloutPct) || rolloutPct < 0 || rolloutPct > 100) {
    throw new Error("rollout must be an integer from 0 to 100");
  }
  /** @type {Record<string, OtaBuild>} */
  const builds = {};
  for (const { chip, merged } of images) {
    const app = appSlice(merged);
    const sha256 = createHash("sha256").update(app).digest("hex");
    const fields = { chip, version, size: app.length, sha256 };
    const sig = sign("sha256", Buffer.from(otaMessage(fields)), privateKeyPem).toString("base64");
    builds[chip] = {
      url: `${urlBase}/probeharbor-probe-${chip}.bin?v=${version}`,
      offset: OTA_APP_OFFSET,
      size: app.length,
      sha256,
      sig,
    };
  }
  return { format: 1, version, rollout_pct: rolloutPct, builds };
}

/**
 * What the probe checks, in the same order. Returns null when good, else why not.
 * @param {{ manifest: OtaManifest, chip: string, publicKeyPem: string, app?: Buffer, runningVersion?: string }} input
 * @returns {string | null}
 */
export function checkOtaEntry({ manifest, chip, publicKeyPem, app, runningVersion }) {
  const entry = manifest?.builds?.[chip];
  if (!entry) return "no build for this chip";
  if (runningVersion && compareVersions(manifest.version, runningVersion) <= 0) return "not newer";
  const message = otaMessage({ chip, version: manifest.version, size: entry.size, sha256: entry.sha256 });
  const key = createPublicKey(publicKeyPem);
  if (!verify("sha256", Buffer.from(message), key, Buffer.from(entry.sig, "base64"))) return "bad signature";
  if (app) {
    if (app.length !== entry.size) return "wrong size";
    if (createHash("sha256").update(app).digest("hex") !== entry.sha256) return "wrong hash";
  }
  return null;
}

/**
 * The public key as the C header the firmware compiles in.
 * @param {string} publicKeyPem
 */
export function publicKeyHeader(publicKeyPem) {
  const lines = publicKeyPem.trim().split("\n").map((line) => `    "${line}\\n"`);
  return `// Generated by \`pnpm firmware:keygen\`: the public half of the OTA signing key.
// Probes only install images whose manifest entry this key verifies.
// Replacing it means probes built with the old key reject new updates.
#pragma once
static const char OTA_PUBLIC_KEY_PEM[] =
${lines.join("\n")};
`;
}

/**
 * Read the PEM back out of the header (to check a key pair matches before publishing).
 * @param {string} header
 * @returns {string | null}
 */
export function publicKeyFromHeader(header) {
  const lines = [...header.matchAll(/^\s*"([^"]*)\\n"/gm)].map((m) => m[1]);
  return lines.length ? `${lines.join("\n")}\n` : null;
}
