#!/usr/bin/env node
/**
 * List every es/fr/de/pt-br translation file for the i18n Worker
 * (workers/i18n). Writes workers/i18n/src/modules.generated.ts.
 *
 *   node scripts/gen-i18n-catalog.mjs          write the file
 *   node scripts/gen-i18n-catalog.mjs --check  exit 1 if it is stale
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "workers/i18n/src/modules.generated.ts");
const LOCALES = ["es", "fr", "de", "pt-br"];

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const full = path.join(dir, d.name);
    return d.isDirectory() ? walk(full) : [full];
  });
}

export function listTranslationFiles() {
  const i18n = path.join(root, "src/i18n");
  const rel = (f) => path.relative(root, f).replaceAll("\\", "/");
  const messages = walk(path.join(i18n, "messages"))
    .map(rel)
    .filter((f) => LOCALES.some((l) => f.endsWith(`/${l}.ts`)) && !f.endsWith(".test.ts"));
  const content = walk(path.join(i18n, "content"))
    .map(rel)
    .filter((f) => /^src\/i18n\/content\/[^/]+\/(es|fr|de|pt-br)\/[^/]+\.ts$/.test(f) && !f.endsWith(".test.ts"));
  return [...messages, ...content].sort();
}

export function renderModules(files) {
  const lines = [
    "// Generated by scripts/gen-i18n-catalog.mjs. Do not edit.",
    "// Run `node scripts/gen-i18n-catalog.mjs` after adding a translation file.",
  ];
  for (const [i, f] of files.entries()) lines.push(`import m${i} from "../../../${f}";`);
  lines.push("", "export const MODULES: Record<string, { default: unknown }> = {");
  for (const [i, f] of files.entries()) lines.push(`  "${f}": { default: m${i} },`);
  lines.push("};", "");
  return lines.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = renderModules(listTranslationFiles());
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(out, "utf8");
    } catch {}
    if (current !== next) {
      console.error("workers/i18n/src/modules.generated.ts is stale: run node scripts/gen-i18n-catalog.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(out, next);
    console.log(`Wrote ${path.relative(root, out)}`);
  }
}
