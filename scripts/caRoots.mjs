/**
 * Root certificates the probe trusts for probeharbor.dev (firmware F2).
 *
 * The site is behind Cloudflare, whose Universal SSL certificates come
 * from Let's Encrypt, Google Trust Services or SSL.com, so the probe
 * carries those CAs' current roots, taken from the Mozilla root store that
 * ships with Node (tls.rootCertificates). They are given to mbedtls as
 * trust anchors (WiFiClientSecure::setCACert), which also handles the
 * cross-signed chain probeharbor.dev sends (GTS Root R4 cross-signed by
 * GlobalSign Root CA, which Mozilla no longer lists).
 *
 * If Cloudflare ever moves to a CA not listed here, probes fall back to
 * unverified posting with a warning, and a signed OTA update can ship a
 * new list.
 */
import { X509Certificate } from "node:crypto";

/** Subject CNs, in the order they're written to the header. */
export const ROOT_CNS = [
  "ISRG Root X1",
  "ISRG Root X2",
  "GTS Root R1",
  "GTS Root R3",
  "GTS Root R4",
  "SSL.com TLS RSA Root CA 2022",
  "SSL.com TLS ECC Root CA 2022",
  "SSL.com Root Certification Authority RSA",
  "SSL.com Root Certification Authority ECC",
];

/** Used by test builds only: a real root that doesn't sign probeharbor.dev's chain. */
export const UNRELATED_TEST_CN = "ISRG Root X2";

/**
 * @param {readonly string[]} pems  e.g. tls.rootCertificates
 * @returns {{ cn: string, pem: string, validTo: string }[]}
 */
export function selectRoots(pems) {
  const byCn = new Map();
  for (const pem of pems) {
    const cert = new X509Certificate(pem);
    const cn = /(?:^|\n)CN=([^\n]+)/.exec(cert.subject)?.[1];
    if (cn && cert.ca) byCn.set(cn, { cn, pem: pem.trim(), validTo: cert.validTo });
  }
  const missing = ROOT_CNS.filter((cn) => !byCn.has(cn));
  if (missing.length) throw new Error(`root store lacks: ${missing.join(", ")}`);
  return ROOT_CNS.map((cn) => byCn.get(cn));
}

/** @param {string} pem */
function cString(pem) {
  return `${pem
    .split("\n")
    .map((line) => `    "${line}\\n"`)
    .join("\n")}`;
}

/**
 * The C header the firmware compiles in.
 * @param {{ cn: string, pem: string, validTo: string }[]} roots
 * @param {string} source  where the roots came from (for the comment)
 */
export function caRootsHeader(roots, source) {
  const list = roots.map((r) => `//   ${r.cn} (until ${r.validTo})`).join("\n");
  const unrelated = roots.find((r) => r.cn === UNRELATED_TEST_CN);
  return `// Generated by \`pnpm firmware:roots\` from ${source}. Do not edit.
// Trust anchors for probeharbor.dev (Cloudflare: Let's Encrypt, Google Trust
// Services, SSL.com):
${list}
#pragma once
static const char CA_ROOTS_PEM[] =
${roots.map((r) => cString(r.pem)).join("\n")};
#ifdef PROBE_TEST_HOOKS
// TTTEST tlsbad: a real root that doesn't sign probeharbor.dev's chain.
static const char CA_UNRELATED_TEST_PEM[] =
${cString(unrelated.pem)};
#endif
`;
}
