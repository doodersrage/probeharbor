"""Turn the production public-schema dump into the Neon baseline migration.

One-off tool kept so the baseline can be reviewed and regenerated:

  pg_restore --schema-only --no-owner --no-privileges -n public \
    -f /tmp/prod-public-schema.sql backups/<dump>.dump
  node db/tools/better-auth-schema.mjs > /tmp/better-auth.sql   # needs an empty local Postgres
  python3 db/tools/baseline-from-supabase-dump.py /tmp/prod-public-schema.sql \
    /tmp/better-auth.sql db/migrations/0001_baseline.sql
"""
import re, sys
src, ba_sql, out = sys.argv[1], sys.argv[2], sys.argv[3]
s = open(src).read()

# 1. pg_dump preamble/meta-commands: drop \restrict lines, SETs and the empty search_path.
s = re.sub(r"^\\(un)?restrict .*\n", "", s, flags=re.M)
s = re.sub(r"^SET [a-z_]+ = .*;\n", "", s, flags=re.M)
s = s.replace("SELECT pg_catalog.set_config('search_path', '', false);\n", "")

# 2. Row rules: every CREATE POLICY statement goes (they guarded Supabase's public API).
policies = re.findall(r"^CREATE POLICY .*?;\n", s, flags=re.M | re.S)
s = re.sub(r"(--\n-- Name: [^\n]*Type: POLICY;[^\n]*\n--\n\n)?^CREATE POLICY .*?;\n", "", s, flags=re.M | re.S)

# 3. Helpers that read the Supabase session (auth.uid()); only the dropped rules used them.
dropped_fns = []
for fn in ("is_household_member", "is_household_editor", "is_household_manager"):
    pat = re.compile(r"--\n-- Name: " + fn + r"\(uuid\); Type: FUNCTION;[^\n]*\n--\n\nCREATE FUNCTION public\." + fn + r"\(.*?\n\$\$;\n", re.S)
    s, n = pat.subn("", s)
    assert n == 1, fn
    dropped_fns.append(fn)

# 4. Supabase's user table -> Better Auth's.
n_fk = s.count("REFERENCES auth.users(id)")
s = s.replace("REFERENCES auth.users(id)", "REFERENCES public.auth_users(id)")
s = s.replace("from auth.users u", "from public.auth_users u")
s = s.replace("u.created_at", 'u."createdAt"')
s = s.replace("SET search_path TO 'public', 'auth'", "SET search_path TO 'public'")

# 5. Tidy blank runs left by removals.
s = re.sub(r"\n{4,}", "\n\n\n", s)

leftover = re.findall(r"auth\.(uid|users|jwt|role)\b|\bto (authenticated|anon)\b|service_role", s, flags=re.I)
assert not leftover, leftover

header = f"""-- 0001_baseline: ProbeHarbor schema for Neon (Postgres 18) + Better Auth.
--
-- Source: production public schema from backups/probeharbor-20261107T130635Z.dump
-- (Supabase, Postgres 17.6), taken with pg_restore --schema-only --no-owner
-- --no-privileges -n public, then changed by db/tools/baseline-from-supabase-dump.py:
--   * Better Auth tables (auth_*) added, generated by better-auth 1.7.18 with
--     generateId "uuid" and the twoFactor, passkey and bearer plugins. The Better
--     Auth config in step 4 must use the same model names.
--   * {n_fk} foreign keys moved from auth.users(id) to public.auth_users(id).
--     User ids stay the same UUIDs, so no other table changes.
--   * The two Supabase signup triggers now fire on public.auth_users.
--   * {len(policies)} row rules (CREATE POLICY) removed. They guarded Supabase's
--     public database API, which Neon will not have: only the Worker connects,
--     with the owner role. Row level security stays enabled on every table, so
--     any other role sees no rows. Household access is enforced in app code.
--   * Removed {", ".join(dropped_fns[:2])},
--     {dropped_fns[2]}: they read the Supabase session (auth.uid())
--     and only those rules used them.
--   * count_managed_users / list_managed_users read public.auth_users.
--   * EXECUTE on functions revoked from PUBLIC (only the owner role calls them).
--   * Built-in groups seeded (admin, user, member, pro, portfolio), as the
--     Supabase migrations did; signup fails without the 'user' group.

"""

ba = open(ba_sql).read().strip()
# Better Auth DDL uses unqualified names; qualify them.
ba = re.sub(r'(create table|references|on) "(auth_[a-z_]+)"', r'\1 public."\2"', ba)

extra = """

-- Profile settings that lived in Supabase user_metadata (locale, °C, active
-- household, dashboard preferences, github_id, ...). Same JSON, keyed by user.
CREATE TABLE public.user_profiles (
    user_id uuid PRIMARY KEY REFERENCES public.auth_users(id) ON DELETE CASCADE,
    metadata jsonb DEFAULT '{}'::jsonb NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL
);
ALTER TABLE public.user_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auth_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auth_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auth_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auth_verifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auth_two_factors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auth_passkeys ENABLE ROW LEVEL SECURITY;

"""

tail = """

-- Signup triggers (were on auth.users). Names kept, so they fire in the same
-- order as before: add_to_user_group, then ensure_household.
CREATE TRIGGER on_auth_user_created_add_to_user_group
    AFTER INSERT ON public.auth_users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user_group_membership();
CREATE TRIGGER on_auth_user_created_ensure_household
    AFTER INSERT ON public.auth_users
    FOR EACH ROW EXECUTE FUNCTION public.ensure_user_household();

-- Built-in groups (seeded by the Supabase migrations).
INSERT INTO public.groups (name)
SELECT g FROM unnest(ARRAY['admin', 'user', 'member', 'pro', 'portfolio']) AS g
WHERE NOT EXISTS (SELECT 1 FROM public.groups WHERE name = g);

-- Only the owner role runs these; no other role may call them.
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC;
"""
open(out, "w").write(header + "-- SQL functions below refer to tables created after them.\nSET check_function_bodies = false;\n\n-- Better Auth tables\n" + ba + "\n" + extra + s.strip() + "\n" + tail)
print(f"policies removed: {len(policies)}; fks moved: {n_fk}; functions dropped: {dropped_fns}")
